"""
Fitting the hard-coded constants once, and writing them into the package as code.

The idea: "no training" should mean the forecast system needs nothing but an analysis and a best track when it
runs -- not that it was never calibrated. Every number the system relies on is fitted here, once, on data
strictly older than (or disjoint from) the seasons it is judged on, and then *written into*
:mod:`naturev1.cyclone.coefficients` as Python literals with their provenance:

* CLIPER and SHIFOR on 1980-2014 best tracks (35 years, ~80,000 fixes, all basins);
* the consensus weights, SHIPS-style regression and LGEM growth rates on the 2016/2017/2019 hindcast seasons;
* the genesis logistic model on the same three seasons;
* none of it on 2018/2020/2021/2022, the seasons every reported result comes from.

The written module is plain data: reading it needs no fitting code, no data and no randomness.
"""

from __future__ import annotations

import datetime as dt
import json
import pprint
from pathlib import Path

import numpy as np

HEADER = '''# Copyright 2026 Nathan. Apache-2.0.
"""
Hard-coded constants of the tropical-cyclone physics, generated by :mod:`naturev1.cyclone.fit`.

Do not edit by hand: regenerate with ``naturev1.cyclone.fit.write_coefficients``. Provenance of every table is in
:data:`PROVENANCE`; nothing here was fitted on the 2018, 2020, 2021 or 2022 seasons the benchmark reports.
"""

'''


def _plain(value):
    """Literal-safe, rounded copy (numpy to lists; NaN stays NaN, written as ``nan``)."""
    if isinstance(value, dict):
        return {str(k): _plain(v) for k, v in value.items()}
    if isinstance(value, (list, tuple, np.ndarray)):
        return [_plain(v) for v in (value.tolist() if isinstance(value, np.ndarray) else value)]
    if isinstance(value, (float, np.floating)):
        return float("nan") if not np.isfinite(value) else round(float(value), 5)
    if isinstance(value, (np.integer,)):
        return int(value)
    return value


def write_coefficients(tables: dict, path: str | Path, provenance: dict) -> Path:
    """Write ``{NAME: table}`` as module-level constants (plus ``PROVENANCE``) into ``path``."""
    path = Path(path)
    lines = [HEADER, "nan = float(\"nan\")\n\n"]
    for name, table in tables.items():
        literal = pprint.pformat(_plain(table), width=118, compact=True, sort_dicts=False)
        lines.append(f"{name} = {literal}\n\n")
    stamp = {"generated": dt.datetime.now(dt.timezone.utc).strftime("%Y-%m-%d %H:%M UTC"), **provenance}
    lines.append(f"PROVENANCE = {pprint.pformat(_plain(stamp), width=118, sort_dicts=False)}\n")
    path.write_text("".join(lines))
    return path


def fit_climatology_tables(history_cases, leads) -> dict:
    """CLIPER and SHIFOR from historical cases (best tracks only)."""
    from .cliper import fit_cliper
    from .intensity import fit_shifor

    return {"CLIPER": fit_cliper(history_cases, leads), "SHIFOR": fit_shifor(history_cases, leads)}


def fit_consensus_table(cases, forecasts: dict, members, reference: str = "cliper") -> dict:
    """Along/cross-track consensus weights over ``members`` (``forecasts[name]``: ``(N, L, 2)``)."""
    from .consensus import fit_consensus

    stack = np.stack([forecasts[m] for m in members], 2)
    w = fit_consensus(cases, stack, reference=list(members).index(reference))
    return {"members": list(members), "reference": w["reference"], "along": w["along"], "cross": w["cross"]}


def load_json(path: str | Path) -> dict:
    return json.loads(Path(path).read_text())


